#!/usr/bin/env python3
from pathlib import Path
import base64,re,subprocess
root=Path(__file__).resolve().parents[1]
s='// Code generated by tools/generate_images.py. DO NOT EDIT.\n//go:build js || sdl\n\npackage main\n\nfunc init() {\nTileImgs = map[string][]byte{}\n'
for p in sorted((root/'tiles').glob('*.png')):
 key=re.sub(r'-upper-([a-z])$',lambda m:'-'+m[1].upper(),p.stem)
 s+='TileImgs["'+key+'"] = []byte(`'+base64.b64encode(p.read_bytes()).decode()+'`)\n'
(root/'images.go').write_text(s+'}\n');subprocess.run(['gofmt','-w',str(root/'images.go')],check=True)
